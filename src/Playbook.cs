/// <summary>Одна команда из тех, что доступны нейросети. Аргумент в угловых скобках обязателен,
/// в квадратных — необязательный, пустой — команда без аргумента.</summary>
internal readonly record struct Directive(string Prefix, string Argument, string Group)
{
    /// <summary>Префиксы сверяются по нормальному тексту, поэтому «вперёд» записано как «вперед».</summary>
    public string Spelled => Argument.Length == 0 ? Prefix : $"{Prefix} {Argument}";

    public bool NeedsArgument => Argument.StartsWith('<');
}

/// <summary>Что нейросеть знает о помощнике: инструкция и список команд, которые передаются ей
